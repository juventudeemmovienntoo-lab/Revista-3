create table if not exists public.community_notes (
  id bigint generated by default as identity primary key,
  author text not null check (char_length(author) between 2 and 28),
  content text not null check (char_length(content) between 3 and 150),
  color text not null check (color in ('yellow', 'lilac', 'blue', 'orange', 'pink')),
  owner_token text,
  created_at timestamptz not null default now()
);

-- Migração segura para projetos que já tinham a tabela community_notes.
alter table public.community_notes add column if not exists owner_token text;

create table if not exists public.community_posts (
  id bigint generated by default as identity primary key,
  author text not null check (char_length(author) between 2 and 28),
  title text not null check (char_length(title) between 3 and 60),
  content text not null check (char_length(content) between 3 and 400),
  likes integer not null default 0 check (likes >= 0),
  owner_token text,
  created_at timestamptz not null default now()
);

-- Migração segura para projetos que já tinham a tabela community_posts.
alter table public.community_posts add column if not exists owner_token text;

alter table public.community_notes enable row level security;
alter table public.community_posts enable row level security;

-- Visitantes podem ler e criar publicações. A exclusão é feita somente pelas funções abaixo, com token de propriedade.
drop policy if exists "notes_public_read" on public.community_notes;
create policy "notes_public_read" on public.community_notes for select to anon, authenticated using (true);
drop policy if exists "notes_public_insert" on public.community_notes;
create policy "notes_public_insert" on public.community_notes for insert to anon, authenticated with check (
  char_length(author) between 2 and 28 and char_length(content) between 3 and 150
  and color in ('yellow', 'lilac', 'blue', 'orange', 'pink')
);

drop policy if exists "posts_public_read" on public.community_posts;
create policy "posts_public_read" on public.community_posts for select to anon, authenticated using (true);
drop policy if exists "posts_public_insert" on public.community_posts;
create policy "posts_public_insert" on public.community_posts for insert to anon, authenticated with check (
  char_length(author) between 2 and 28 and char_length(title) between 3 and 60
  and char_length(content) between 3 and 400 and likes = 0
);


-- Permite apagar somente o post-it associado ao token secreto deste navegador.
-- O token não é incluído nas leituras públicas do mural.
create or replace function public.delete_community_note(note_id bigint, note_owner_token text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare rows_deleted integer;
begin
  if note_owner_token is null or char_length(note_owner_token) < 32 then
    return false;
  end if;

  delete from public.community_notes
  where id = note_id and owner_token = note_owner_token;

  get diagnostics rows_deleted = row_count;
  return rows_deleted > 0;
end;
$$;

revoke all on function public.delete_community_note(bigint, text) from public;
grant execute on function public.delete_community_note(bigint, text) to anon, authenticated;

