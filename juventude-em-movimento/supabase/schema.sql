-- Curtidas são feitas por uma função atômica, sem liberar atualização direta da tabela.
create or replace function public.like_community_post(post_id bigint)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare new_likes integer;
begin
  update public.community_posts
  set likes = likes + 1
  where id = post_id
  returning likes into new_likes;
  if new_likes is null then
    raise exception 'Publicação não encontrada';
  end if;
  return new_likes;
end;
$$;

revoke all on function public.like_community_post(bigint) from public;
grant execute on function public.like_community_post(bigint) to anon, authenticated;

grant usage, select on sequence public.community_notes_id_seq to anon, authenticated;
grant usage, select on sequence public.community_posts_id_seq to anon, authenticated;
